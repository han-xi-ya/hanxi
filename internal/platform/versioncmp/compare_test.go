package versioncmp

import "testing"

// 用例从 everything/version 同款测试原样迁入，另补 BCU 四段场景。
func TestCompare(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		{"1.5.0.1422b", "1.5.0.1422", 1},  // 修正版比初版新
		{"1.5.0.1422c", "1.5.0.1422b", 1}, // 尾字母字典序
		{"1.5.0.1423", "1.5.0.1422b", 1},  // 数字段优先于字母后缀
		{"1.4.1.1032", "1.5.0.1422b", -1}, // 主版本
		{"1.5.0.1422b", "1.5.0.1422b", 0}, // 相等
		{"1.5.2", "1.5.9.0", -1},          // 段数不同
		{"1.10.0", "1.9.0", 1},            // 数值比较而非字典序
		{"1.5.0.1422b", "1.5.0.1422a", 1}, // a < b
		{"", "1.0", -1},                   // 空串非规范 → 劣后于规范串（不 panic）
		// 2026-10-26 审查批次契约订正：旧断言为 {"v1.2.3","1.2.3",1}，即"带 v 前缀
		// 被当成文本、字典序更大"。该语义正是缺陷本体——账本展示令牌（v2.16.1）与
		// 远程 tag（2.16.1）本是同一版本，旧语义下既判不出相等、又使多段数字退化为
		// 字典序（见下方 v 前缀组）。现由 Compare 统一归一，两处形态等价。
		{"v1.2.3", "1.2.3", 0},
		{"V1.2.3", "1.2.3", 0},  // 大写 V 同样归一（用户手输/无头调用形态）
		{"6.2.0", "6.1.0.1", 1}, // BCU：主版本优先
		{"6.2.0.1", "6.2.0", 1}, // BCU：段多者胜
		{"6.1.0.1", "6.1.0", 1}, // BCU：三/四段
		{"6.10.0", "6.9.0", 1},  // 两位段数值比较

		// —— 带 v 前缀的已装令牌：必须先归一再数值比较（T2 取证的现行缺陷形态）——
		{"v2.16.1", "v2.9.0", 1},  // Termora：字典序会误判 2.9.0 更新
		{"v2.9.0", "v2.10.0", -1}, // WindTerm 同族
		{"v1.106.0", "v1.100.0", 1},
		{"v63.1.0", "63.1.0", 0}, // 剥前缀后与裸号等价

		// —— 导入兜底目录（非规范）恒劣后于规范版本，不得冒充"最新已装"——
		{"imported-6e449042eec3", "1.5.0.1422b", -1},
		{"1.5.0", "imported-6e449042eec3", 1},
		{"vimported-6e449042eec3", "v1.4.1", -1},                 // 带 v 前缀的兜底令牌同样劣后
		{"imported-20260101-120000", "63.1.0", -1},               // 历史秒级时间戳形态
		{"imported-6e449042eec3", "imported-20260101-120000", 1}, // 同为非规范：字典序有确定序、不 panic
	}
	for _, c := range cases {
		if got := Compare(c.a, c.b); got != c.want {
			t.Errorf("Compare(%q, %q) = %d, 期望 %d", c.a, c.b, got, c.want)
		}
	}
}
