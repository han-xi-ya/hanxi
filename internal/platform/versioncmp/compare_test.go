package versioncmp

import "testing"

// 用例从 everything/version 同款测试原样迁入，另补 BCU 四段场景。
func TestCompare(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		{"1.5.0.1422b", "1.5.0.1422", 1},  // 修正版比初版新
		{"1.5.0.1422c", "1.5.0.1422b", 1}, // 尾字母字典序
		{"1.5.0.1423", "1.5.0.1422b", 1},  // 数字段优先于字母后缀
		{"1.4.1.1032", "1.5.0.1422b", -1}, // 主版本
		{"1.5.0.1422b", "1.5.0.1422b", 0}, // 相等
		{"1.5.2", "1.5.9.0", -1},          // 段数不同
		{"1.10.0", "1.9.0", 1},            // 数值比较而非字典序
		{"1.5.0.1422b", "1.5.0.1422a", 1}, // a < b
		{"", "1.0", -1},                   // 空串非规范 → 劣后于规范串（不 panic）
		// 2026-10-26 审查批次契约订正：旧断言为 {"v1.2.3","1.2.3",1}，即"带 v 前缀
		// 被当成文本、字典序更大"。该语义正是缺陷本体——账本展示令牌（v2.16.1）与
		// 远程 tag（2.16.1）本是同一版本，旧语义下既判不出相等、又使多段数字退化为
		// 字典序（见下方 v 前缀组）。现由 Compare 统一归一，两处形态等价。
		{"v1.2.3", "1.2.3", 0},
		{"V1.2.3", "1.2.3", 0},  // 大写 V 同样归一（用户手输/无头调用形态）
		{"6.2.0", "6.1.0.1", 1}, // BCU：主版本优先
		{"6.2.0.1", "6.2.0", 1}, // BCU：段多者胜
		{"6.1.0.1", "6.1.0", 1}, // BCU：三/四段
		{"6.10.0", "6.9.0", 1},  // 两位段数值比较

		// —— 带 v 前缀的已装令牌：必须先归一再数值比较（T2 取证的现行缺陷形态）——
		{"v2.16.1", "v2.9.0", 1},  // Termora：字典序会误判 2.9.0 更新
		{"v2.9.0", "v2.10.0", -1}, // WindTerm 同族
		{"v1.106.0", "v1.100.0", 1},
		{"v63.1.0", "63.1.0", 0}, // 剥前缀后与裸号等价

		// —— 导入兜底目录（非规范）恒劣后于规范版本，不得冒充"最新已装"——
		{"imported-6e449042eec3", "1.5.0.1422b", -1},
		{"1.5.0", "imported-6e449042eec3", 1},
		{"vimported-6e449042eec3", "v1.4.1", -1},                 // 带 v 前缀的兜底令牌同样劣后
		{"imported-20260101-120000", "63.1.0", -1},               // 历史秒级时间戳形态
		{"imported-6e449042eec3", "imported-20260101-120000", 1}, // 同为非规范：字典序有确定序、不 panic

		// —— 预发布形态必须是规范串并按 semver §11 定序（2026-11-11 感知链取证）——
		// 旧语义把带横杠的 beta 整体判为非规范，规则 2 让任何规范稳定版都"更新"，
		// 于是 Termora（本机 v2.0.0-beta.16 / 稳定通道 v1.0.17）与 Paseo（本机
		// 0.16.0-beta.1 / 0.15.4）追更后"可用更新"红点永不熄灭。
		{"2.0.0-beta.16", "1.0.17", 1},   // Termora 实况：beta 核心更高即更新
		{"0.16.0-beta.1", "0.15.4", 1},   // Paseo 实况：minor 16 > 15
		{"v2.0.0-beta.16", "v1.0.17", 1}, // 带 v 前缀的已装令牌同样归一后比较
		{"1.0.17", "2.0.0-beta.16", -1},  // 反向不自洽即为错
		{"1.0.0", "1.0.0-beta.1", 1},     // 正式版优先于其预发布
		{"1.0.0-beta.1", "1.0.0-beta.2", -1},
		{"1.0.0-beta.2", "1.0.0-beta.16", -1}, // 数字标识符按数值，非字典序（"2" < "16"）
		{"1.0.0-beta", "1.0.0-beta.1", -1},    // 全等时标识符少者小
		{"1.0.0-alpha", "1.0.0-beta", -1},     // 字母标识符字典序
		{"1.0.0-1", "1.0.0-alpha", -1},        // 数字标识符恒小于字母标识符
		{"2026-03-26", "2025-11-01", 1},       // 日期形态（rammap 账目）：核心年份先决
		{"2026-03-26", "2026-03-26", 0},
		{"1.5.0.1422b", "1.5.0.1422b-beta.1", 1}, // 尾字母核心 + 预发布可叠加
		{"1.2.3-beta", "1.2.3", -1},

		// —— 数值核心不成立的横杠形态仍判非规范，不得因为"有横杠"就升格 ——
		{"imported-6e449042eec3", "1.2.3-beta", -1},          // 兜底目录劣后于预发布版
		{"1.2.3-beta", "imported-6e449042eec3", 1},           // 反向同结论
		{"0.8.98", "0.8.98.removing-1792028345934887800", 1}, // 落位中途临时目录不是新版
		{"1.0.0+build2", "1.0.0", -1},                        // 带 build 元数据：维持非规范档位
		{"1.2.3-", "1.2.3", -1},                              // 空预发布串非法 → 非规范
		{"1.2.3-beta..1", "1.2.3", -1},                       // 空标识符非法 → 非规范
	}
	for _, c := range cases {
		if got := Compare(c.a, c.b); got != c.want {
			t.Errorf("Compare(%q, %q) = %d, 期望 %d", c.a, c.b, got, c.want)
		}
	}
}

// TestIsCanonical 锁判据与 Compare 同源：带 v 前缀的展示令牌、预发布形态都算规范串；
// 兜底目录/临时目录/build 元数据/杂串算非规范（Compare 对它们退化为字典序 + 档位劣后）。
func TestIsCanonical(t *testing.T) {
	canonical := []string{
		"1.2.3", "v1.2.3", "V1.2.3", "4.15", "6.2.0.1", "1.5.0.1422b", "2026-03-26",
		"2.0.0-beta.16", "v2.0.0-beta.16", "0.16.0-beta.1", "1.0.0-rc.1", "1.0.0-beta",
		" 1.2.3 ",
	}
	for _, v := range canonical {
		if !IsCanonical(v) {
			t.Errorf("IsCanonical(%q) = false, 期望 true", v)
		}
	}
	nonCanonical := []string{
		"", "latest", "nightly-build", "imported-6e449042eec3", "vimported-6e449042eec3",
		"0.8.98.removing-1792028345934887800", "1.0.0+build2", "1.2.3-", "1.2.3-beta..1",
		"1.2.3_4", "x1.2.3",
	}
	for _, v := range nonCanonical {
		if IsCanonical(v) {
			t.Errorf("IsCanonical(%q) = true, 期望 false", v)
		}
	}
}
